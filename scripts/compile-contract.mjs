#!/usr/bin/env node
/**
 * Compiles contracts/CryptoVaultToken.sol with solc and writes the ABI +
 * creation bytecode into src/lib/contracts/erc20.ts.
 *
 * Compiling at build time (rather than shipping solc-js to the browser) keeps
 * ~10 MB of WASM out of the bundle and makes the deployed bytecode
 * reproducible: anyone can re-run `npm run compile:contract` and diff.
 *
 *   npm run compile:contract
 */
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { createRequire } from 'node:module';

const require = createRequire(import.meta.url);
const solc = require('solc');

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const SOURCE = 'CryptoVaultToken.sol';
const sourcePath = join(root, 'contracts', SOURCE);

/** Resolve `@openzeppelin/...` imports out of node_modules. */
function findImport(importPath) {
  try {
    const full = importPath.startsWith('@')
      ? join(root, 'node_modules', importPath)
      : resolve(join(root, 'contracts'), importPath);
    return { contents: readFileSync(full, 'utf8') };
  } catch (err) {
    return { error: `Could not find ${importPath}: ${err.message}` };
  }
}

const input = {
  language: 'Solidity',
  sources: { [SOURCE]: { content: readFileSync(sourcePath, 'utf8') } },
  settings: {
    optimizer: { enabled: true, runs: 200 },
    // OpenZeppelin 5.6 uses MCOPY, so Cancun is the floor. Ethereum mainnet,
    // Sepolia and every major L2 have been past Cancun since 2024; if you need
    // to deploy on a chain that has not forked, pin @openzeppelin/contracts
    // to 5.1.x and drop this back to 'shanghai'.
    evmVersion: 'cancun',
    outputSelection: { '*': { '*': ['abi', 'evm.bytecode.object', 'metadata'] } },
  },
};

const output = JSON.parse(solc.compile(JSON.stringify(input), { import: findImport }));

const errors = (output.errors ?? []).filter((e) => e.severity === 'error');
if (errors.length) {
  for (const e of errors) console.error(e.formattedMessage);
  process.exit(1);
}
for (const w of output.errors ?? []) {
  if (w.severity === 'warning') console.warn('warning:', w.formattedMessage.trim().split('\n')[0]);
}

const artifact = output.contracts[SOURCE].CryptoVaultToken;
const bytecode = `0x${artifact.evm.bytecode.object}`;
const version = solc.version();

const banner = `// AUTO-GENERATED by scripts/compile-contract.mjs - do not edit by hand.
// Source:  contracts/CryptoVaultToken.sol
// Compiler: solc ${version}
// Settings: optimizer enabled, 200 runs, evmVersion cancun
// Regenerate with: npm run compile:contract
`;

const body = `${banner}
export const ERC20_COMPILER_VERSION = ${JSON.stringify(version)};

export const ERC20_ABI = ${JSON.stringify(artifact.abi, null, 2)} as const;

export const ERC20_BYTECODE = ${JSON.stringify(bytecode)};

/** Rough gas needed to put this contract on chain. Used for the cost preview. */
export const ERC20_DEPLOY_GAS_ESTIMATE = 1_800_000n;
`;

const outDir = join(root, 'src', 'lib', 'contracts');
mkdirSync(outDir, { recursive: true });
writeFileSync(join(outDir, 'erc20.ts'), body);

console.log(`compiled CryptoVaultToken with solc ${version}`);
console.log(`bytecode: ${(bytecode.length / 2 - 1).toLocaleString()} bytes`);
console.log('wrote src/lib/contracts/erc20.ts');
